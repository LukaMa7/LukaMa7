def finding_block(doc, f):
    """f: dict(no, title, codes(list main), alt(list), simple, proves, not_proves, missing, judgment, why,
    alt_answers, remediation[(action, owner, date)], assumption?, suggested?)"""
    doc.h(f"الملاحظة {f['no']}: {f['title']}", 2)
    for c in f['codes']:
        doc.p(official(c), size=10.5)
    rows = [('[[شرح مبسط]]', f['simple'])]
    rows.append(('ما يثبته الدليل', f['proves']))
    rows.append(('ما لا يثبته الدليل', f['not_proves']))
    rows.append(('المعلومات الناقصة / الطلبات', f['missing']))
    rows.append(('الحكم المقترح', '**' + f['judgment'] + '**\n' + f['why']))
    rows.append(('إجابات بديلة مقبولة', f['alt_answers']))
    if f.get('suggested'):
        rows.append(('[[تطبيق مقترح]]', f['suggested']))
    if f.get('assumption'):
        rows.append(('[[افتراض تدريبي]]', f['assumption']))
    doc.kv(rows, widths=(3.8, 13.2), size=10)
    if f.get('remediation'):
        doc.p('خطة المعالجة المقترحة (افتراضية):', bold=True, size=10.5, keep=True)
        doc.table(['الإجراء', 'المالك', 'الموعد الافتراضي'], f['remediation'], widths=[10.5, 4.0, 2.5], size=9.5)


