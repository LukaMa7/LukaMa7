JUDGMENTS = '☐ مطبق    ☐ مطبق جزئياً    ☐ غير مطبق    ☐ لا يمكن الحكم'


def trainee_header_table(doc, app_label):
    doc.kv([('اسم المتدرب', ''), ('التاريخ', ''), ('التطبيق', app_label), ('الوقت المستغرق', '')],
           widths=(4.0, 13.0), size=10.5, min_height=0.8)


def finding_card(doc, i):
    doc.h(f'بطاقة الملاحظة رقم {i}', 3)
    rows = [
        ('الضابط (الرمز ونصه المختصر)', ''),
        ('المطلوب (ماذا يطلب الضابط بلغتك)', ''),
        ('ما يثبته الدليل (اذكر الدليل/الورقة والصف أو التاريخ)', ''),
        ('ما لا يثبته الدليل', ''),
        ('المعلومات الناقصة / الطلبات', ''),
        ('الحكم', JUDGMENTS),
        ('المبرر', ''),
        ('خطة المعالجة — الإجراء', ''),
        ('خطة المعالجة — المالك', ''),
        ('خطة المعالجة — الموعد الافتراضي', ''),
    ]
    heights = [1.1, 1.3, 2.0, 1.6, 1.6, 0.8, 1.6, 1.6, 0.8, 0.8]
    doc.kv(rows, widths=(5.0, 12.0), size=10.5, min_height=heights)


def build_template(path, header, title, app_label, intro, n_cards, summary_controls, extra=None):
    d = RDoc(header, title=title)
    d.title_block(title, 'القالب الفارغ لإجابة المتدرب', kicker='ECC-2:2024 · تطبيق عملي')
    trainee_header_table(d, app_label)
    d.h('كيف تملأ هذا القالب', 2)
    for line in intro:
        d.bullet(line)
    d.bullet('الحكم: اختر واحداً فقط: مطبق، أو مطبق جزئياً، أو غير مطبق، أو لا يمكن الحكم (عندما تكون الأدلة غير كافية للحكم؛ واذكر ما تحتاجه).')
    d.bullet('اكتب المبرر من الأدلة المقدمة فقط. إن احتجت دليلاً غير موجود فاكتبه في خانة «المعلومات الناقصة / الطلبات» ولا تفترض وجوده.')
    d.bullet('خطة المعالجة: إجراء محدد يمكن التحقق من تنفيذه، ومالك من أصحاب الأدوار في ملف الجهة، وموعد افتراضي.')
    d.h('الجزء أ: بطاقات الملاحظات', 1)
    d.p('بطاقة لكل ملاحظة. إن احتجت بطاقات أكثر فانسخ آخر بطاقة.', size=10.5, color='555555')
    for i in range(1, n_cards + 1):
        finding_card(d, i)
    d.h('الجزء ب: الحكم الإجمالي لكل ضابط في النطاق', 1)
    d.table(['الضابط', 'الحكم الإجمالي', 'المبرر المختصر (أرقام البطاقات المرتبطة)'],
            [[c, '', ''] for c in summary_controls], widths=[3.0, 3.5, 10.5], size=10.5)
    if extra:
        extra(d)
    d.h('ملاحظات عامة أو افتراضات اعتمدتها', 2)
    d.kv([('ملاحظاتك', '')], widths=(4.0, 13.0), min_height=3.0)
    return d.save(path)


