REPORT_AT = '2026-09-30 17:00'
LIMIT_MIN = 60  # training assumption: the entity's procedure defines "immediately" as within one hour

def _delay(end, *done):
    from datetime import datetime
    f = lambda x: datetime.strptime(x, '%Y-%m-%d %H:%M')
    last = max(f(d) for d in done) if all(done) else f(REPORT_AT)
    m = int((last - f(end)).total_seconds() // 60)
    return m, all(done)

def _fmt(m):
    d, r = divmod(m, 1440); h, mi = divmod(r, 60)
    if d >= 2 and not h and not mi:
        return f'{d} يوماً'
    parts = ([f'{d} أيام' if 2 < d < 11 else (f'{d} يوماً' if d >= 11 else ('يوم' if d == 1 else 'يومان'))] if d else []) + \
            ([f'{h} ساعة' if h > 10 or h == 1 else (f'{h} ساعات' if h > 2 else 'ساعتان')] if h else []) + ([f'{mi} دقائق' if 2 < mi < 11 else (f'{mi} دقيقة' if mi != 2 else 'دقيقتان')] if mi else [])
    return ' و'.join(parts)

def leaver_rows():
    rows = []
    for who, end, ad, erp in LEAVERS:
        m, done = _delay(end, ad, erp)
        late = m > LIMIT_MIN
        judge = 'في الموعد' if not late else ('نشط بعد الانتهاء' if not done else 'متأخر')
        rows.append([who, end, ad or 'لم يُعطَّل', erp or 'لم يُعطَّل', (_fmt(m) + (' حتى تاريخ التقرير' if not done else '')), judge])
    return rows

